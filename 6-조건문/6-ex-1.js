let fruite = "grape";

switch (fruite) {
 case "banana":
  console.log("바나나입니다");
  break;
 case "apple":
  console.log("사과입니다.");
  break;
 case "orange":
  console.log("오렌지입니다.");
  break;
 case "grape":
  console.log("포도입니다.");
  break;
 default:
  console.log("알수 없는 과일 입니다.");
  break;
}

